/// How a dependency is referenced from the example's Cargo.toml.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum DepKind {
    /// Repo crate or external crate: resolved via the workspace root's
    /// `[workspace.dependencies]` (path entry → path dep; version entry →
    /// explicit version copied verbatim).
    Resolved,
    /// Inline version spec (embassy crates — NOT workspace deps).
    InlineVersion,
    /// Pure-TOML blox: path dependency into target/bloxide-generated/crates.
    GeneratedBlox,
}

/// Collect the `[dependencies]` of the example crate.
///
/// Each entry is (crate_name, features, kind), sorted by name. This mirrors
/// the derivation the app-level Cargo.toml generation used: always-required
/// framework crates, runtime-specific crates, per-actor blox/message/
/// context/impl crates, and factory-injection crates.
fn collect_dependencies(
    config: &SystemConfig,
    discovered: &BTreeMap<String, util::DiscoveredBlox>,
    blox_configs: &BTreeMap<String, BloxConfig>,
) -> anyhow::Result<BTreeMap<String, (Vec<String>, DepKind)>> {
    let active_features = crate::infer_active_features(config, blox_configs);
    let mut deps: BTreeMap<String, (Vec<String>, DepKind)> = BTreeMap::new();

    // ── Always-required deps ───────────────────────────────────────────────
    deps.insert(
        "bloxide-core".to_string(),
        (vec!["std".to_string()], DepKind::Resolved),
    );
    deps.insert(
        "bloxide-log".to_string(),
        (vec!["log".to_string()], DepKind::Resolved),
    );
    deps.insert(
        "bloxide-supervisor".to_string(),
        (vec!["std".to_string()], DepKind::Resolved),
    );
    // The system-level generated supervisor spec imports types from
    // bloxide-child-management (ChildGroup, ChildCtrl), so it must be
    // a dependency of every example that uses the supervisor.
    deps.insert(
        "bloxide-child-management".to_string(),
        (vec!["std".to_string()], DepKind::Resolved),
    );

    // ── Runtime-specific deps ──────────────────────────────────────────────
    match config.system.runtime.as_str() {
        "tokio" => {
            deps.insert("bloxide-tokio".to_string(), (vec![], DepKind::Resolved));
            deps.insert("tokio".to_string(), (vec![], DepKind::Resolved));
            deps.insert("tracing".to_string(), (vec![], DepKind::Resolved));
            deps.insert(
                "tracing-subscriber".to_string(),
                (vec![], DepKind::Resolved),
            );
            deps.insert("tracing-log".to_string(), (vec![], DepKind::Resolved));
        }
        "embassy" => {
            deps.insert(
                "bloxide-embassy".to_string(),
                (vec!["std".to_string()], DepKind::Resolved),
            );
            // embassy crates are NOT workspace deps — inline version specs.
            deps.insert(
                "embassy-executor".to_string(),
                (
                    vec!["arch-std".to_string(), "executor-thread".to_string()],
                    DepKind::InlineVersion,
                ),
            );
            deps.insert("embassy-sync".to_string(), (vec![], DepKind::InlineVersion));
            deps.insert(
                "embassy-time".to_string(),
                (
                    vec!["std".to_string(), "generic-queue-8".to_string()],
                    DepKind::InlineVersion,
                ),
            );
            deps.insert(
                "critical-section".to_string(),
                (vec!["std".to_string()], DepKind::InlineVersion),
            );
            deps.insert("static_cell".to_string(), (vec![], DepKind::Resolved));
            deps.insert("tracing".to_string(), (vec![], DepKind::Resolved));
            deps.insert(
                "tracing-subscriber".to_string(),
                (vec![], DepKind::Resolved),
            );
        }
        "test" => {
            // Test runtime — minimal deps.
        }
        other => {
            eprintln!("bloxide: warning: unknown runtime '{}'", other);
        }
    }

    // ── Per-actor deps ─────────────────────────────────────────────────────
    for actor in &config.actors {
        let is_timer = actor.kind.as_deref() == Some("timer");

        // The blox crate itself. Pure-TOML bloxes (discovered under a
        // `bloxes/` directory) are materialized into target/bloxide-generated
        // and referenced by path; everything else resolves via the workspace.
        let blox_name = &actor.blox;
        let features = active_features
            .get(blox_name)
            .cloned()
            .unwrap_or_default()
            .into_iter()
            .collect::<Vec<_>>();
        let kind = match discovered.get(blox_name).map(|b| b.kind) {
            Some(util::BloxSourceKind::PureToml) => DepKind::GeneratedBlox,
            _ => DepKind::Resolved,
        };
        deps.insert(blox_name.clone(), (features, kind));

        if is_timer {
            // bloxide-timer is already added as the blox crate.
            // Ensure std feature is included.
            let entry = deps
                .get_mut("bloxide-timer")
                .ok_or_else(|| anyhow::anyhow!("timer actor requires bloxide-timer dependency"))?;
            if !entry.0.contains(&"std".to_string()) {
                entry.0.push("std".to_string());
            }
        }

        // Message crates: extract from the blox.toml's event.mailboxes[].message_path.
        // A message_path may reference multiple crates in nested generics, e.g.
        // "pool_messages::SpawnedWorker<bloxide_peers::PeerCtrl<...>, R>" — we
        // need all of them as Cargo.toml dependencies.
        if let Some(blox_config) = blox_configs.get(blox_name) {
            if let Some(event) = &blox_config.event {
                for mailbox in &event.mailboxes {
                    let path = mailbox.message_path.as_deref().unwrap_or(&mailbox.message);
                    for crate_part in extract_crates_from_path(path) {
                        let cargo_name = crate_part.replace('_', "-");
                        deps.entry(cargo_name)
                            .or_insert_with(|| (vec![], DepKind::Resolved));
                    }
                }
            }

            // Also check context.imports for message crate references.
            if let Some(ctx) = &blox_config.context {
                for imp in &ctx.imports {
                    // imports are like "ping_pong_messages::PingPongMsg"
                    // or "bloxide_timer::{TimerCommand, TimerId}"
                    if let Some(crate_part) = imp.split("::").next() {
                        // Skip std/alloc/bloxide_core etc — only add external
                        // message crates (they end with "_messages").
                        if crate_part.ends_with("_messages") {
                            let cargo_name = crate_part.replace('_', "-");
                            deps.entry(cargo_name)
                                .or_insert_with(|| (vec![], DepKind::Resolved));
                        }
                    }
                }

                // Add context action crates — these are the crates that
                // provide the concrete action functions referenced in the
                // generated spec_skeleton.rs (e.g. blox_ctx_rounds,
                // blox_ctx_ping_pong, bloxide_timer).
                for action in &ctx.actions {
                    if let Some(ref crate_name) = action.crate_name {
                        let cargo_name = crate_name.replace('_', "-");
                        deps.entry(cargo_name)
                            .or_insert_with(|| (vec![], DepKind::Resolved));
                    }
                }
            }
        }

        // Concrete action impl crate (system codegen). Forward the actor's
        // features to the impl crate so that feature-gated action functions
        // are compiled in.
        if let Some(impl_crate) = &actor.impl_crate {
            let cargo_name = impl_crate.replace('_', "-");
            let entry = deps
                .entry(cargo_name)
                .or_insert_with(|| (vec![], DepKind::Resolved));
            for feat in &actor.features {
                if !entry.0.contains(feat) {
                    entry.0.push(feat.clone());
                }
            }
        }

        // Factory injection crates.
        for src in actor.inject.values() {
            if src.source == "factory" {
                if let Some(crate_name) = &src.crate_name {
                    // crate_name uses underscores (e.g. "tokio_pool_demo_impl")
                    // — convert to hyphens for Cargo.toml.
                    let cargo_name = crate_name.replace('_', "-");
                    deps.entry(cargo_name)
                        .or_insert_with(|| (vec![], DepKind::Resolved));
                }
                // The generated main.rs composes the factory with the
                // platform spawn (`::bloxide_spawn::spawn_actor_task`), so
                // the example needs bloxide-spawn as a direct dependency.
                deps.entry("bloxide-spawn".to_string())
                    .or_insert_with(|| (vec!["std".to_string()], DepKind::Resolved));
            }
        }
    }

    Ok(deps)
}

/// External (version-based) dependency specs from the workspace root's
/// `[workspace.dependencies]` table: crate name → raw TOML value.
fn workspace_version_deps(workspace_root: &Path) -> anyhow::Result<BTreeMap<String, toml::Value>> {
    let content = std::fs::read_to_string(workspace_root.join("Cargo.toml"))?;
    let parsed: toml::Value = toml::from_str(&content)?;
    let mut map = BTreeMap::new();
    if let Some(deps) = parsed
        .get("workspace")
        .and_then(|w| w.get("dependencies"))
        .and_then(|d| d.as_table())
    {
        for (name, value) in deps {
            if value.get("path").is_none() {
                map.insert(name.clone(), value.clone());
            }
        }
    }
    Ok(map)
}

/// Render one dependency line for the example manifest.
fn dep_line(
    name: &str,
    features: &[String],
    kind: DepKind,
    prefix: &str,
    ws_paths: &BTreeMap<String, String>,
    ws_versions: &BTreeMap<String, toml::Value>,
) -> anyhow::Result<String> {
    let feat_suffix = |features: &[String]| {
        if features.is_empty() {
            String::new()
        } else {
            format!(", features = {}", toml_string_list(features))
        }
    };

    match kind {
        DepKind::GeneratedBlox => {
            // From examples/<name> to crates/<blox>: ../../crates/<blox>.
            Ok(format!(
                "{} = {{ path = \"../../crates/{}\"{} }}\n",
                name,
                name,
                feat_suffix(features)
            ))
        }
        DepKind::Resolved => {
            if let Some(path) = ws_paths.get(name) {
                Ok(format!(
                    "{} = {{ path = \"{}{}\"{} }}\n",
                    name,
                    prefix,
                    path,
                    feat_suffix(features)
                ))
            } else if let Some(value) = ws_versions.get(name) {
                Ok(render_version_dep(name, value, features))
            } else {
                anyhow::bail!(
                    "dependency \"{}\" (required by the system.toml) has no entry in the workspace root's [workspace.dependencies]",
                    name
                )
            }
        }
        DepKind::InlineVersion => {
            // Inline version specs for non-workspace deps (embassy crates).
            let feats = feat_suffix(features);
            let line = match name {
                "embassy-executor" => {
                    format!("embassy-executor = {{ version = \"0.9\"{} }}\n", feats)
                }
                "embassy-sync" => format!("embassy-sync = {{ version = \"0.7\"{} }}\n", feats),
                "embassy-time" => format!("embassy-time = {{ version = \"0.5\"{} }}\n", feats),
                "critical-section" => {
                    format!("critical-section = {{ version = \"1.2\"{} }}\n", feats)
                }
                _ => anyhow::bail!("no inline version spec known for dependency \"{}\"", name),
            };
            Ok(line)
        }
    }
}

/// Render an external dependency, copying the version spec from the root
/// `[workspace.dependencies]` entry verbatim (string or inline table form),
/// merging any extra features the example requires.
fn render_version_dep(name: &str, value: &toml::Value, extra_features: &[String]) -> String {
    match value {
        toml::Value::String(version) => {
            if extra_features.is_empty() {
                format!("{} = \"{}\"\n", name, version)
            } else {
                format!(
                    "{} = {{ version = \"{}\", features = {} }}\n",
                    name,
                    version,
                    toml_string_list(extra_features)
                )
            }
        }
        toml::Value::Table(table) => {
            let version = table.get("version").and_then(|v| v.as_str());
            let mut features: Vec<String> = table
                .get("features")
                .and_then(|f| f.as_array())
                .map(|arr| {
                    arr.iter()
                        .filter_map(|f| f.as_str().map(String::from))
                        .collect()
                })
                .unwrap_or_default();
            for feat in extra_features {
                if !features.contains(feat) {
                    features.push(feat.clone());
                }
            }
            let mut parts = Vec::new();
            if let Some(version) = version {
                parts.push(format!("version = \"{}\"", version));
            }
            if !features.is_empty() {
                parts.push(format!("features = {}", toml_string_list(&features)));
            }
            format!("{} = {{ {} }}\n", name, parts.join(", "))
        }
        _ => format!("{} = {}\n", name, value),
    }
}

/// Render the materialized example crate's `Cargo.toml`.
pub fn example_manifest(
    config: &SystemConfig,
    crate_name: &str,
    discovered: &BTreeMap<String, util::DiscoveredBlox>,
    blox_configs: &BTreeMap<String, BloxConfig>,
    workspace_root: &Path,
    example_dir: &Path,
    dev_crates: &BTreeSet<String>,
) -> anyhow::Result<String> {
    let ws_paths = workspace_dep_paths(workspace_root)?;
    let ws_versions = workspace_version_deps(workspace_root)?;
    let (version, edition, license) = workspace_package_values(workspace_root);
    let prefix = relative_prefix(workspace_root, example_dir)?;

    let mut out = String::new();
    out.push_str(MANIFEST_HEADER);
    out.push('\n');
    out.push_str("[package]\n");
    out.push_str(&format!("name = \"{}\"\n", crate_name));
    out.push_str(&format!("version = \"{}\"\n", version));
    out.push_str(&format!("edition = \"{}\"\n", edition));
    if let Some(license) = &license {
        out.push_str(&format!("license = \"{}\"\n", license));
    }
    out.push_str("publish = false\n\n");

    // [dependencies]
    let deps = collect_dependencies(config, discovered, blox_configs)?;
    out.push_str("[dependencies]\n");
    for (name, (features, kind)) in &deps {
        out.push_str(&dep_line(
            name,
            features,
            *kind,
            &prefix,
            &ws_paths,
            &ws_versions,
        )?);
    }
    out.push('\n');

    // [dev-dependencies] — crates the integration tests import directly
    // (derived from the test sources; see module docs). The scan also yields
    // lowercase MODULE segments of multi-segment paths (e.g. `lifecycle` in
    // `bloxide_core::lifecycle::...`) — candidates that resolve to no known
    // crate (workspace dependency or discovered blox) are not crates and are
    // dropped here.
    let self_underscored = crate_name.replace('-', "_");
    let mut dev_names: Vec<String> = dev_crates
        .iter()
        .map(|u| u.replace('_', "-"))
        .filter(|name| *name != crate_name && *name != self_underscored)
        .collect();
    dev_names.sort();
    let mut dev_section = String::new();
    for name in &dev_names {
        // Kind + features mirror the [dependencies] entry when present;
        // otherwise the crate must resolve via [workspace.dependencies].
        let (features, kind) = match deps.get(name) {
            Some((features, kind)) => (features.clone(), *kind),
            None if ws_paths.contains_key(name) || ws_versions.contains_key(name) => {
                (vec![], DepKind::Resolved)
            }
            None => continue,
        };
        dev_section.push_str(&dep_line(
            name,
            &features,
            kind,
            &prefix,
            &ws_paths,
            &ws_versions,
        )?);
    }
    if !dev_section.is_empty() {
        out.push_str("[dev-dependencies]\n");
        out.push_str(&dev_section);
        out.push('\n');
    }

    // [build-dependencies] — the codegen itself, for the re-sync build.rs.
    out.push_str("[build-dependencies]\n");
    out.push_str(&format!(
        "bloxide-codegen = {{ path = \"{}{}\" }}\n",
        prefix, CODEGEN_CRATE_PATH
    ));

    Ok(out)
}

/// Render the materialized example crate's `src/lib.rs` — a uniform library
/// target exposing the system-generated concrete specs so integration tests
/// can import them (`<example>::generated::...`).
pub fn lib_rs_source(crate_name: &str) -> String {
    format!(
        "// Copyright 2025 Bloxide, all rights reserved\n\
         // Auto-generated by bloxide-codegen from system.toml — do not edit by hand; regenerate with `cargo blox generate`.\n\
         //! Library target for the `{crate_name}` example.\n\
         //!\n\
         //! Exposes the system-generated concrete specs (`src/generated/`) so the\n\
         //! integration tests in `tests/` can drive the real machines — the binary\n\
         //! (`src/main.rs`) keeps its own private `mod generated;`.\n\
         \n\
         pub mod generated;\n"
    )
}

/// Render the materialized example crate's `build.rs`. Paths are relative to
/// the crate dir (build scripts run with the package root as cwd), keeping
/// the generated tree relocatable.
pub fn build_rs_source(
    system_toml: &Path,
    workspace_root: &Path,
    example_dir: &Path,
) -> anyhow::Result<String> {
    let prefix = relative_prefix(workspace_root, example_dir)?;
    let system_rel = system_toml.strip_prefix(workspace_root).map_err(|_| {
        anyhow::anyhow!(
            "source system.toml {} is not under the workspace root {}",
            system_toml.display(),
            workspace_root.display()
        )
    })?;
    let source_dir = format!("{}{}", prefix, system_rel.parent().unwrap().display());
    let system_path = format!("{}{}", prefix, system_rel.display());

    Ok(format!(
        "// Copyright 2025 Bloxide, all rights reserved\n\
         // Auto-generated by bloxide-codegen — do not edit by hand; regenerate with `cargo blox generate`.\n\
         //! Build script: keeps this materialized crate in sync with its source\n\
         //! system.toml after the initial `cargo blox generate`. Regenerates\n\
         //! `src/main.rs`, `src/generated/`, `src/lib.rs`, and `Cargo.toml`, and\n\
         //! re-copies `tests/`, whenever the source system.toml or tests directory\n\
         //! changes — plain `cargo build` / `cargo test` / `cargo run` stay fresh\n\
         //! without re-running `cargo blox generate`.\n\
         //!\n\
         //! Note: a brand-new test file added to the source tests/ directory is\n\
         //! copied here on the next build, but cargo may need one extra invocation\n\
         //! to discover the new test target.\n\
         \n\
         fn main() {{\n\
         \x20   let system_toml = \"{system_path}\";\n\
         \x20   let tests_dir = \"{source_dir}/tests\";\n\
         \x20   println!(\"cargo:rerun-if-changed={{}}\", system_toml);\n\
         \x20   if std::path::Path::new(tests_dir).is_dir() {{\n\
         \x20       println!(\"cargo:rerun-if-changed={{}}\", tests_dir);\n\
         \x20       for entry in std::fs::read_dir(tests_dir).into_iter().flatten().flatten() {{\n\
         \x20           let path = entry.path();\n\
         \x20           if path.extension().is_some_and(|ext| ext == \"rs\") {{\n\
         \x20               println!(\"cargo:rerun-if-changed={{}}\", path.display());\n\
         \x20           }}\n\
         \x20       }}\n\
         \x20   }}\n\
         \x20   bloxide_codegen::example_crate::sync_from_source(\n\
         \x20       std::path::Path::new(system_toml),\n\
         \x20       std::path::Path::new(\"{prefix}\"),\n\
         \x20       std::path::Path::new(\".\"),\n\
         \x20   )\n\
         \x20   .expect(\"failed to regenerate example crate from system.toml\");\n\
         }}\n"
    ))
}

/// `["a", "b"]` TOML array literal.
fn toml_string_list(items: &[String]) -> String {
    let inner = items
        .iter()
        .map(|i| format!("\"{}\"", i))
        .collect::<Vec<_>>()
        .join(", ");
    format!("[{}]", inner)
}

/// Generate the concrete `*_spec_skeleton.rs` files (actors + supervisors)
/// and the `mod.rs` declaring them. The `src/generated/` directory is fully
/// owned: files no longer emitted are removed.
fn sync_generated_specs(
    config: &SystemConfig,
    blox_configs: &BTreeMap<String, BloxConfig>,
    example_dir: &Path,
) -> anyhow::Result<()> {
    // Collect all spec files: actors + supervisors
    let mut all_spec_files = Vec::new();

    if !config.actors.is_empty() {
        let spec_files =
            crate::system_spec::generate_concrete_spec_files(blox_configs, &config.actors)?;
        all_spec_files.extend(spec_files);
    }

    // Concrete specs for supervisors referenced in [[supervision]]
    for sup in &config.supervision {
        let supervisor_crate = &sup.supervisor;
        if let Some(blox_config) = blox_configs.get(supervisor_crate) {
            let blox_crate_path = format!("::{}", supervisor_crate.replace('-', "_"));
            let code = crate::system_spec::generate_concrete_spec_skeleton(
                blox_config,
                None, // supervisors don't have impl_crate
                supervisor_crate,
                &blox_crate_path,
                None, // no active feature for supervisor
            )?;
            all_spec_files.push((supervisor_crate.replace('-', "_").to_lowercase(), code));
        }
    }

    let generated_dir = example_dir.join("src").join("generated");
    if all_spec_files.is_empty() {
        if generated_dir.is_dir() {
            std::fs::remove_dir_all(&generated_dir)?;
        }
        return Ok(());
    }

    std::fs::create_dir_all(&generated_dir)?;
    let mut mod_content = String::from(
        "// Copyright 2025 Bloxide, all rights reserved\n\
         // Auto-generated module. Do not edit manually.\n\
         //! Generated by bloxide-codegen from system.toml — do not edit by hand; regenerate with `cargo blox generate`.\n",
    );
    let mut fresh: BTreeSet<String> = BTreeSet::new();
    for (actor_name, spec_code) in &all_spec_files {
        let module_name = actor_name.replace('-', "_").to_lowercase() + "_spec_skeleton";
        let filename = format!("{}.rs", module_name);
        // Format before writing so `cargo fmt --check` passes on generated
        // files and re-generation is byte-identical (idempotent).
        let spec_code = rustfmt_source(spec_code)?;
        fresh.insert(filename.clone());
        write_if_changed(&generated_dir.join(&filename), &spec_code)?;
        mod_content.push_str(&format!("pub mod {};\n", module_name));
        mod_content.push_str(&format!(
            "#[allow(unused_imports)]\npub use {}::*;\n",
            module_name
        ));
    }
    fresh.insert("mod.rs".to_string());
    write_if_changed(&generated_dir.join("mod.rs"), &mod_content)?;

    // The generated/ directory is fully owned — remove stale files.
    for entry in std::fs::read_dir(&generated_dir)?.flatten() {
        let name = entry.file_name().to_string_lossy().to_string();
        if name.ends_with(".rs") && !fresh.contains(&name) {
            std::fs::remove_file(entry.path())?;
        }
    }
    Ok(())
}


//! Materialization of pure-TOML example crates (system.toml sources).
//!
//! An example is a `system.toml`-only source under `examples/<name>/` (plus
//! an optional `tests/` directory). `cargo blox generate` materializes a
//! complete crate per example into
//! `target/bloxide-generated/examples/<crate-name>/`:
//!
//! ```text
//! target/bloxide-generated/
//!   Cargo.toml                       ← generated workspace (members = ["crates/*", "examples/*"])
//!   examples/<crate-name>/
//!     Cargo.toml                     ← generated (deps derived from system.toml + blox.tomls)
//!     build.rs                       ← generated (re-syncs from the source system.toml)
//!     src/main.rs                    ← system wiring (the binary)
//!     src/lib.rs                     ← generated (`pub mod generated;` for tests)
//!     src/generated/*_spec_skeleton.rs + mod.rs  ← concrete specs
//!     tests/*.rs                     ← mirrored from examples/<name>/tests/
//! ```
//!
//! The crate name is `[system] name` (falling back to the source directory
//! name), so existing test imports like `tokio_pool_demo::generated::...`
//! keep working.
//!
//! The example crate is a member of the GENERATED workspace, not the repo
//! workspace, so `{ workspace = true }` cannot resolve: every repo crate
//! (blox crates, messages, context, impl, runtime, supervisor, spawn)
//! becomes a path dependency — into `../..//crates/` for materialized blox
//! crates, and relative paths like `../../../../crates/...` for repo crates
//! (resolved via the workspace root's `[workspace.dependencies]` table, same
//! as [`crate::blox_crate`]). External deps (tokio, tracing, …) get explicit
//! versions copied from the root `[workspace.dependencies]` entries. Embassy
//! deps keep their inline-version behavior.
//!
//! Dev-dependencies: integration tests import crates directly (e.g.
//! `pool_blox::PoolCtx`). The crates a test may import are DERIVED FROM THE
//! TEST SOURCES: every lowercase `ident::` path prefix in `tests/*.rs` is a
//! crate candidate (skipping `std`/`core`/`alloc`/`crate`/`self`/`super`/
//! `generated` and the example crate itself); candidates that resolve via
//! the root `[workspace.dependencies]` or the discovered bloxes become
//! `[dev-dependencies]` entries, resolved exactly like regular dependencies.
//! Candidates matching no known crate are lowercase module segments of
//! multi-segment paths (e.g. `lifecycle` in `bloxide_core::lifecycle::…`)
//! and are dropped. Feature lists are copied from the `[dependencies]`
//! entry when the crate appears there.
//!
//! Every write goes through `write_if_changed` so repeated `cargo blox
//! generate` runs (and the generated `build.rs` re-sync) are byte-identical
//! and mtime-stable.


/// Crates referenced by the example's `tests/*.rs` sources: every lowercase
/// `ident::` path prefix is treated as a crate name (underscored), skipping
/// std/core/alloc/crate/self/super/generated. The example crate itself is
/// filtered out by the caller's manifest builder.
pub fn test_imported_crates(tests_dir: &Path) -> BTreeSet<String> {
    let mut crates = BTreeSet::new();
    if !tests_dir.is_dir() {
        return crates;
    }
    for entry in std::fs::read_dir(tests_dir).into_iter().flatten().flatten() {
        let path = entry.path();
        if path.extension().is_some_and(|ext| ext == "rs") {
            if let Ok(content) = std::fs::read_to_string(&path) {
                scan_crate_prefixes(&content, &mut crates);
            }
        }
    }
    crates
}

/// Scan Rust source for `<ident>::` path prefixes where `ident` is an
/// all-lowercase snake_case segment (Rust crate names in paths are
/// lowercase; types are UpperCamel and are ignored).
fn scan_crate_prefixes(content: &str, out: &mut BTreeSet<String>) {
    let bytes = content.as_bytes();
    let is_ident = |b: u8| b.is_ascii_alphanumeric() || b == b'_';
    let mut i = 0;
    while i < bytes.len() {
        if (bytes[i].is_ascii_lowercase() || bytes[i] == b'_')
            && (i == 0 || !is_ident(bytes[i - 1]))
        {
            let start = i;
            while i < bytes.len() && is_ident(bytes[i]) {
                i += 1;
            }
            let ident = &content[start..i];
            if i + 1 < bytes.len()
                && bytes[i] == b':'
                && bytes[i + 1] == b':'
                && !SCAN_SKIP.contains(&ident)
            {
                out.insert(ident.to_string());
            }
        } else {
            i += 1;
        }
    }
}


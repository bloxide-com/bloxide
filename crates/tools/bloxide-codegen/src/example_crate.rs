/// Manifest path (repo-relative) of the bloxide-codegen crate — every
/// materialized example build-depends on it so its build.rs can re-sync.
const CODEGEN_CRATE_PATH: &str = "crates/tools/bloxide-codegen";

const MANIFEST_HEADER: &str = "# Copyright 2025 Bloxide, all rights reserved\n\
     # Auto-generated by bloxide-codegen from system.toml — do not edit by hand; regenerate with `cargo blox generate`.\n";

/// Identifiers that look like crate prefixes in test sources but are not.
const SCAN_SKIP: [&str; 7] = [
    "std",
    "core",
    "alloc",
    "crate",
    "self",
    "super",
    "generated",
];


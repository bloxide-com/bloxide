/// Derive the example crate name: `[system] name`, falling back to the
/// source directory name.
pub fn example_crate_name(config: &SystemConfig, system_toml: &Path) -> String {
    config.system.name.clone().unwrap_or_else(|| {
        system_toml
            .parent()
            .and_then(|d| d.file_name())
            .and_then(|n| n.to_str())
            .unwrap_or("bloxide-example")
            .to_string()
    })
}

/// Materialize (or re-sync) the example crate for one `system.toml`,
/// computing the target directory
/// (`target/bloxide-generated/examples/<crate-name>`) from the manifest.
/// Returns the crate name.
pub fn sync_example(system_toml: &Path, workspace_root: &Path) -> anyhow::Result<String> {
    let content = std::fs::read_to_string(system_toml)?;
    let config: SystemConfig = toml::from_str(&content)?;
    let crate_name = example_crate_name(&config, system_toml);
    let example_dir = workspace_root
        .join(GENERATED_WORKSPACE_DIR)
        .join("examples")
        .join(&crate_name);
    sync_example_crate(system_toml, workspace_root, &example_dir)
}

/// Materialize (or re-sync) the crate for one example `system.toml`.
///
/// - `system_toml` — the source manifest (`<workspace>/examples/<name>/system.toml`).
/// - `workspace_root` — the repository workspace root.
/// - `example_dir` — `target/bloxide-generated/examples/<crate-name>`.
///
/// Returns the crate name. Idempotent: only files whose content changed are
/// rewritten.
pub fn sync_example_crate(
    system_toml: &Path,
    workspace_root: &Path,
    example_dir: &Path,
) -> anyhow::Result<String> {
    let content = std::fs::read_to_string(system_toml)?;
    let config: SystemConfig = toml::from_str(&content)?;
    let crate_name = example_crate_name(&config, system_toml);

    // Normalize to absolute paths (see blox_crate::sync_blox_crate): the
    // example dir is created first so it can be canonicalized on a fresh
    // bootstrap.
    std::fs::create_dir_all(example_dir)?;
    let system_toml = std::fs::canonicalize(system_toml)?;
    let workspace_root = std::fs::canonicalize(workspace_root)?;
    let example_dir = std::fs::canonicalize(example_dir)?;

    // Blox configs (message/context dep derivation) + source kinds
    // (pure-TOML bloxes become path deps into ../..//crates/).
    let discovered = util::discover_bloxes(&workspace_root)?;
    let blox_configs: BTreeMap<String, BloxConfig> = discovered
        .iter()
        .map(|(k, v)| (k.clone(), v.config.clone()))
        .collect();

    // Crates the integration tests import directly (dev-dependencies).
    let source_tests = system_toml.parent().unwrap().join("tests");
    let dev_crates = test_imported_crates(&source_tests);

    // Cargo.toml
    let manifest = example_manifest(
        &config,
        &crate_name,
        &discovered,
        &blox_configs,
        &workspace_root,
        &example_dir,
        &dev_crates,
    )?;
    write_if_changed(&example_dir.join("Cargo.toml"), &manifest)?;

    // build.rs (re-sync trigger for plain cargo builds)
    let build_rs = build_rs_source(&system_toml, &workspace_root, &example_dir)?;
    write_if_changed(&example_dir.join("build.rs"), &build_rs)?;

    // src/main.rs (system wiring — already rustfmt'd by system_wiring::generate)
    let active_features = crate::infer_active_features(&config, &blox_configs);
    let main_rs = crate::system_wiring::generate(&config, &blox_configs, &active_features)?;
    write_if_changed(&example_dir.join("src").join("main.rs"), &main_rs)?;

    // src/generated/*_spec_skeleton.rs + mod.rs (concrete specs)
    sync_generated_specs(&config, &blox_configs, &example_dir)?;

    // src/lib.rs (uniform library target so tests can import the crate)
    let lib = lib_rs_source(&crate_name);
    write_if_changed(&example_dir.join("src").join("lib.rs"), &lib)?;

    // tests/ — mirror the source tests directory (if any).
    sync_tests_dir(&source_tests, &example_dir.join("tests"))?;

    Ok(crate_name)
}

/// Entry point used by the generated `build.rs`: re-sync the crate at
/// `example_dir` from its source `system_toml` (paths may be relative —
/// build scripts run with the package root as cwd).
pub fn sync_from_source(
    system_toml: &Path,
    workspace_root: &Path,
    example_dir: &Path,
) -> anyhow::Result<()> {
    sync_example_crate(system_toml, workspace_root, example_dir)?;
    Ok(())
}


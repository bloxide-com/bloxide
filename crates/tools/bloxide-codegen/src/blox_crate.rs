/// Render the materialized crate's `Cargo.toml`.
pub fn crate_manifest(
    config: &BloxConfig,
    crate_name: &str,
    workspace_root: &Path,
    crate_dir: &Path,
) -> anyhow::Result<String> {
    let ws_paths = workspace_dep_paths(workspace_root)?;
    let (version, edition, license) = workspace_package_values(workspace_root);
    let prefix = relative_prefix(workspace_root, crate_dir)?;

    let mut out = String::new();
    out.push_str(MANIFEST_HEADER);
    out.push('\n');
    out.push_str("[package]\n");
    out.push_str(&format!("name = \"{}\"\n", crate_name));
    out.push_str(&format!("version = \"{}\"\n", version));
    out.push_str(&format!("edition = \"{}\"\n", edition));
    if let Some(license) = &license {
        out.push_str(&format!("license = \"{}\"\n", license));
    }
    out.push_str("publish = false\n");
    if let Some(desc) = config.package.as_ref().and_then(|p| p.description.as_ref()) {
        out.push_str(&format!("description = \"{}\"\n", desc));
    }
    out.push('\n');

    // [features]
    let features = crate_features(config)?;
    out.push_str("[features]\n");
    for (name, values) in &features {
        out.push_str(&format!("{} = {}\n", name, toml_string_list(values)));
    }
    out.push('\n');

    // [dependencies] — derived + declared extras, sorted by cargo name.
    let mut deps: BTreeMap<String, (String, DepSpec)> = BTreeMap::new();
    for underscored in referenced_crates(config) {
        let cargo_name = underscored.replace('_', "-");
        let path = resolve_dep_path(&ws_paths, &cargo_name)?;
        deps.insert(cargo_name, (path.to_string(), DepSpec::default()));
    }
    if let Some(pkg) = &config.package {
        for (name, spec) in &pkg.dependencies {
            let path = resolve_dep_path(&ws_paths, name)?;
            deps.insert(name.clone(), (path.to_string(), spec.clone()));
        }
    }
    out.push_str("[dependencies]\n");
    for (name, (path, spec)) in &deps {
        out.push_str(&dep_line(name, &prefix, path, spec));
    }
    out.push('\n');

    // [dev-dependencies] — declared only (the blox's tests/ directory).
    let dev_deps = config
        .package
        .as_ref()
        .map(|p| p.dev_dependencies.clone())
        .unwrap_or_default();
    if !dev_deps.is_empty() {
        out.push_str("[dev-dependencies]\n");
        for (name, spec) in &dev_deps {
            let path = resolve_dep_path(&ws_paths, name)?;
            out.push_str(&dep_line(name, &prefix, path, spec));
        }
        out.push('\n');
    }

    // [build-dependencies] — the codegen itself, for the re-sync build.rs.
    out.push_str("[build-dependencies]\n");
    out.push_str(&format!(
        "bloxide-codegen = {{ path = \"{}{}\" }}\n",
        prefix, CODEGEN_CRATE_PATH
    ));

    Ok(out)
}

/// Render the materialized crate's `src/lib.rs`.
///
/// `uses_alloc` should be true when any generated source references `alloc::`
/// (the caller scans the `generate_all` output) — the `extern crate alloc;`
/// line is emitted only then.
pub fn lib_rs_source(config: &BloxConfig, uses_alloc: bool) -> anyhow::Result<String> {
    let actor_name = config
        .actor
        .as_ref()
        .map(|a| a.name.as_str())
        .unwrap_or("Unknown");
    let description = config
        .package
        .as_ref()
        .and_then(|p| p.description.clone())
        .unwrap_or_else(|| format!("{} actor blox — runtime-agnostic.", actor_name));

    // Re-export list: <Actor>Ctx / <Actor>Event / <Actor>Spec / <Actor>State,
    // from whichever sections exist.
    let mut exports: Vec<String> = Vec::new();
    if let Some(ctx) = &config.context {
        exports.push(ctx.name.clone());
    }
    if let Some(event) = &config.event {
        exports.push(event.name.clone());
    }
    if config.actor.is_some() {
        exports.push(format!("{}Spec", actor_name));
        exports.push(format!("{}State", actor_name));
    }
    let export_list = exports.join(", ");

    let features = crate_features(config)?;

    let mut out = String::new();
    out.push_str("// Copyright 2025 Bloxide, all rights reserved\n");
    out.push_str("// Auto-generated by bloxide-codegen from blox.toml — do not edit by hand; regenerate with `cargo blox generate`.\n");
    out.push_str(&format!("//! {}\n", description));
    out.push_str("#![no_std]\n");
    if uses_alloc {
        out.push_str("extern crate alloc;\n");
    }
    out.push('\n');
    if features.contains_key("std") {
        out.push_str("#[cfg(feature = \"std\")]\nextern crate std;\n\n");
    }
    out.push_str("pub mod generated;\n\n");
    if !exports.is_empty() {
        out.push_str("/// Convenience re-exports for wiring sites.\n");
        out.push_str("pub mod prelude {\n");
        out.push_str(&format!("    pub use crate::{{{}}};\n", export_list));
        out.push_str("}\n\n");
        out.push_str(&format!("pub use generated::{{{}}};\n", export_list));
    }
    for c in &config.consts {
        out.push('\n');
        if let Some(doc) = &c.doc {
            out.push_str(&format!("/// {}\n", doc));
        }
        out.push_str(&format!("pub const {}: {} = {};\n", c.name, c.ty, c.value));
    }
    Ok(out)
}

/// Render the materialized crate's `build.rs`. Paths are relative to the
/// crate dir (build scripts run with the package root as cwd), keeping the
/// generated tree relocatable.
pub fn build_rs_source(
    blox_toml: &Path,
    workspace_root: &Path,
    crate_dir: &Path,
) -> anyhow::Result<String> {
    let prefix = relative_prefix(workspace_root, crate_dir)?;
    let blox_rel = blox_toml.strip_prefix(workspace_root).map_err(|_| {
        anyhow::anyhow!(
            "source blox.toml {} is not under the workspace root {}",
            blox_toml.display(),
            workspace_root.display()
        )
    })?;
    let source_dir = format!("{}{}", prefix, blox_rel.parent().unwrap().display());
    let blox_path = format!("{}{}", prefix, blox_rel.display());

    Ok(format!(
        "// Copyright 2025 Bloxide, all rights reserved\n\
         // Auto-generated by bloxide-codegen — do not edit by hand; regenerate with `cargo blox generate`.\n\
         //! Build script: keeps this materialized crate in sync with its source\n\
         //! blox.toml after the initial `cargo blox generate`. Regenerates\n\
         //! `src/generated/`, `src/lib.rs`, and `Cargo.toml`, and re-copies `tests/`,\n\
         //! whenever the source blox.toml or tests directory changes — plain\n\
         //! `cargo build` / `cargo test` stay fresh without re-running `cargo blox generate`.\n\
         //!\n\
         //! Note: a brand-new test file added to the source tests/ directory is\n\
         //! copied here on the next build, but cargo may need one extra invocation\n\
         //! to discover the new test target.\n\
         \n\
         fn main() {{\n\
         \x20   let blox_toml = \"{blox_path}\";\n\
         \x20   let tests_dir = \"{source_dir}/tests\";\n\
         \x20   println!(\"cargo:rerun-if-changed={{}}\", blox_toml);\n\
         \x20   if std::path::Path::new(tests_dir).is_dir() {{\n\
         \x20       println!(\"cargo:rerun-if-changed={{}}\", tests_dir);\n\
         \x20       for entry in std::fs::read_dir(tests_dir).into_iter().flatten().flatten() {{\n\
         \x20           let path = entry.path();\n\
         \x20           if path.extension().is_some_and(|ext| ext == \"rs\") {{\n\
         \x20               println!(\"cargo:rerun-if-changed={{}}\", path.display());\n\
         \x20           }}\n\
         \x20       }}\n\
         \x20   }}\n\
         \x20   bloxide_codegen::blox_crate::sync_from_source(\n\
         \x20       std::path::Path::new(blox_toml),\n\
         \x20       std::path::Path::new(\"{prefix}\"),\n\
         \x20       std::path::Path::new(\".\"),\n\
         \x20   )\n\
         \x20   .expect(\"failed to regenerate blox crate from blox.toml\");\n\
         }}\n"
    ))
}


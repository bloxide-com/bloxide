/// Relative prefix from `crate_dir` back up to `workspace_root`
/// (e.g. `"../../../../"` for `target/bloxide-generated/crates/<name>`).
pub fn relative_prefix(workspace_root: &Path, crate_dir: &Path) -> anyhow::Result<String> {
    let rel = crate_dir.strip_prefix(workspace_root).map_err(|_| {
        anyhow::anyhow!(
            "crate dir {} is not under the workspace root {}",
            crate_dir.display(),
            workspace_root.display()
        )
    })?;
    Ok("../".repeat(rel.components().count()))
}

/// One `[dependencies]` line: `name = { path = "<prefix><path>"[, features = [...]] }`.
fn dep_line(name: &str, prefix: &str, path: &str, spec: &DepSpec) -> String {
    if spec.features.is_empty() {
        format!("{} = {{ path = \"{}{}\" }}\n", name, prefix, path)
    } else {
        format!(
            "{} = {{ path = \"{}{}\", features = {} }}\n",
            name,
            prefix,
            path,
            toml_string_list(&spec.features)
        )
    }
}

/// `["a", "b"]` TOML array literal.
fn toml_string_list(items: &[String]) -> String {
    let inner = items
        .iter()
        .map(|i| format!("\"{}\"", i))
        .collect::<Vec<_>>()
        .join(", ");
    format!("[{}]", inner)
}

/// Write `content` to `path` only when it differs (preserves mtime → cargo
/// caching and idempotent `cargo blox generate`). Creates parent dirs.
pub(crate) fn write_if_changed(path: &Path, content: &str) -> anyhow::Result<()> {
    let needs_write = if path.exists() {
        std::fs::read_to_string(path)? != content
    } else {
        true
    };
    if needs_write {
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        std::fs::write(path, content)?;
    }
    Ok(())
}

/// Mirror `*.rs` files from `source_dir` into `target_dir` (both may not
/// exist). The target directory is fully owned: files that disappeared from
/// the source are removed, and the target directory itself is removed when
/// the source has no tests.
pub(crate) fn sync_tests_dir(source_dir: &Path, target_dir: &Path) -> anyhow::Result<()> {
    let mut sources: BTreeMap<String, PathBuf> = BTreeMap::new();
    if source_dir.is_dir() {
        for entry in std::fs::read_dir(source_dir)?.flatten() {
            let path = entry.path();
            if path.extension().is_some_and(|ext| ext == "rs") {
                sources.insert(entry.file_name().to_string_lossy().to_string(), path);
            }
        }
    }

    if sources.is_empty() {
        if target_dir.is_dir() {
            std::fs::remove_dir_all(target_dir)?;
        }
        return Ok(());
    }

    std::fs::create_dir_all(target_dir)?;
    for (name, src) in &sources {
        let content = std::fs::read_to_string(src)?;
        write_if_changed(&target_dir.join(name), &content)?;
    }
    for entry in std::fs::read_dir(target_dir)?.flatten() {
        let name = entry.file_name().to_string_lossy().to_string();
        if name.ends_with(".rs") && !sources.contains_key(&name) {
            std::fs::remove_file(entry.path())?;
        }
    }
    Ok(())
}

/// Ensure the generated workspace root manifest
/// (`target/bloxide-generated/Cargo.toml`) exists. Called once per
/// `cargo blox generate` run when at least one pure-TOML blox or example
/// (system.toml) was found.
pub fn sync_generated_workspace(workspace_root: &Path) -> anyhow::Result<()> {
    let generated_root = workspace_root.join(GENERATED_WORKSPACE_DIR);
    let content = format!(
        "{}\n[workspace]\nmembers = [\"crates/*\", \"examples/*\"]\nresolver = \"2\"\n",
        WORKSPACE_MANIFEST_HEADER
    );
    write_if_changed(&generated_root.join("Cargo.toml"), &content)
}

/// Repo-relative directories of the impl crates referenced by any
/// `system.toml` (`[[actors]] impl_crate`, plus `source = "factory"`
/// injection crates), resolved via the root `[workspace.dependencies]` table
/// — the same resolution the generated example manifests use. Names with no
/// path entry there are skipped (the example manifest generation reports
/// them as errors when truly required).
///
/// Impl crates path-depend into `target/bloxide-generated/`, so they are
/// excluded from the repo workspace (the root must load before the generated
/// tree exists). They also CANNOT be members of the generated workspace —
/// cargo requires members to be hierarchically below the workspace root.
/// They therefore build as path dependencies of the generated example
/// crates, and `cargo blox test` runs their tests explicitly via
/// `--manifest-path`.
pub fn impl_crate_dirs(workspace_root: &Path) -> Vec<String> {
    let Ok(ws_paths) = workspace_dep_paths(workspace_root) else {
        return Vec::new();
    };
    let mut names: BTreeSet<String> = BTreeSet::new();
    for entry in walkdir::WalkDir::new(workspace_root)
        .into_iter()
        .filter_entry(|e| e.file_name() != "target")
        .filter_map(|e| e.ok())
    {
        if entry.file_name() != "system.toml" {
            continue;
        }
        let Ok(content) = std::fs::read_to_string(entry.path()) else {
            continue;
        };
        let Ok(config) = toml::from_str::<SystemConfig>(&content) else {
            continue;
        };
        for actor in &config.actors {
            if let Some(impl_crate) = &actor.impl_crate {
                names.insert(impl_crate.replace('_', "-"));
            }
            for src in actor.inject.values() {
                if src.source == "factory" {
                    if let Some(crate_name) = &src.crate_name {
                        names.insert(crate_name.replace('_', "-"));
                    }
                }
            }
        }
    }
    names
        .into_iter()
        .filter_map(|name| ws_paths.get(&name).cloned())
        .collect()
}

/// Materialize (or re-sync) the crate for one pure-TOML blox.
///
/// - `blox_toml` — the source blox.toml (`<workspace>/bloxes/<name>/blox.toml`).
/// - `workspace_root` — the repository workspace root.
/// - `crate_dir` — `target/bloxide-generated/crates/<crate-name>`.
///
/// Returns the crate name. Idempotent: only files whose content changed are
/// rewritten.
pub fn sync_blox_crate(
    blox_toml: &Path,
    workspace_root: &Path,
    crate_dir: &Path,
) -> anyhow::Result<String> {
    let content = std::fs::read_to_string(blox_toml)?;
    let config: BloxConfig = toml::from_str(&content)?;
    let crate_name = util::pure_toml_crate_name(&config).ok_or_else(|| {
        anyhow::anyhow!(
            "pure-TOML blox {} has no [actor] section — cannot derive a crate name",
            blox_toml.display()
        )
    })?;

    // Normalize to absolute paths: callers pass anything from absolute paths
    // (cargo blox generate) to `../../../../` and `.` (the generated
    // build.rs, whose cwd is the crate dir). The crate dir is created first
    // so it can be canonicalized on a fresh bootstrap.
    std::fs::create_dir_all(crate_dir)?;
    let blox_toml = std::fs::canonicalize(blox_toml)?;
    let workspace_root = std::fs::canonicalize(workspace_root)?;
    let crate_dir = std::fs::canonicalize(crate_dir)?;

    // Cargo.toml
    let manifest = crate_manifest(&config, &crate_name, &workspace_root, &crate_dir)?;
    write_if_changed(&crate_dir.join("Cargo.toml"), &manifest)?;

    // build.rs (re-sync trigger for plain cargo builds)
    let build_rs = build_rs_source(&blox_toml, &workspace_root, &crate_dir)?;
    write_if_changed(&crate_dir.join("build.rs"), &build_rs)?;

    // src/generated/*.rs (existing generate_all output, rustfmt-formatted
    // exactly like `cargo blox generate`'s in-crate flow).
    let files = crate::generate_all(&config, &crate_name)?;
    let generated_dir = crate_dir.join("src").join("generated");
    std::fs::create_dir_all(&generated_dir)?;
    let mut fresh: BTreeSet<String> = BTreeSet::new();
    let mut uses_alloc = false;
    for (filename, raw) in &files {
        let formatted = rustfmt_source(raw)?;
        if formatted.contains("alloc::") {
            uses_alloc = true;
        }
        fresh.insert(filename.clone());
        write_if_changed(&generated_dir.join(filename), &formatted)?;
    }
    // The generated/ directory is fully owned — remove files that are no
    // longer emitted (e.g. after a section was deleted from the blox.toml).
    for entry in std::fs::read_dir(&generated_dir)?.flatten() {
        let name = entry.file_name().to_string_lossy().to_string();
        if name.ends_with(".rs") && !fresh.contains(&name) {
            std::fs::remove_file(entry.path())?;
        }
    }

    // src/lib.rs
    let lib = lib_rs_source(&config, uses_alloc)?;
    write_if_changed(&crate_dir.join("src").join("lib.rs"), &lib)?;

    // tests/ — mirror the source tests directory (if any).
    let source_tests = blox_toml.parent().unwrap().join("tests");
    sync_tests_dir(&source_tests, &crate_dir.join("tests"))?;

    Ok(crate_name)
}

/// Entry point used by the generated `build.rs`: re-sync the crate at
/// `crate_dir` from its source `blox_toml` (paths may be relative — build
/// scripts run with the package root as cwd).
pub fn sync_from_source(
    blox_toml: &Path,
    workspace_root: &Path,
    crate_dir: &Path,
) -> anyhow::Result<()> {
    sync_blox_crate(blox_toml, workspace_root, crate_dir)?;
    Ok(())
}


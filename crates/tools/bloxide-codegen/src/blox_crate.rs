/// Crates referenced by a blox.toml that become `[dependencies]` of the
/// materialized crate. Underscored crate names (e.g. `bloxide_timer`).
fn referenced_crates(config: &BloxConfig) -> BTreeSet<String> {
    /// Import path prefixes that never name an external crate.
    const SKIP: [&str; 5] = ["crate", "core", "std", "alloc", "Self"];

    let mut crates = BTreeSet::new();
    // The generated code always references ::bloxide_core.
    crates.insert("bloxide_core".to_string());

    if let Some(event) = &config.event {
        for mailbox in &event.mailboxes {
            let path = mailbox.message_path.as_deref().unwrap_or(&mailbox.message);
            crates.extend(extract_crates_from_path(path));
        }
    }

    if let Some(ctx) = &config.context {
        for imp in ctx.imports.iter().chain(ctx.feature_imports.iter()) {
            if let Some(first) = imp.split("::").next() {
                if !SKIP.contains(&first) {
                    crates.insert(first.to_string());
                }
            }
        }
        // Context action crates provide the concrete action functions; the
        // blox crate links them so its `[features]` can forward to them and
        // downstream consumers see a complete dependency graph.
        for action in &ctx.actions {
            if !action.impl_required {
                if let Some(crate_name) = &action.crate_name {
                    crates.insert(crate_name.clone());
                }
            }
        }
    }

    if let Some(topology) = &config.topology {
        for imp in topology
            .spec_imports
            .iter()
            .chain(topology.feature_spec_imports.iter())
        {
            if let Some(first) = imp.split("::").next() {
                if !SKIP.contains(&first) {
                    crates.insert(first.to_string());
                }
            }
        }
    }

    crates
}

/// Feature names referenced by `feature = "..."` gates anywhere in the
/// blox.toml. Each must exist in the materialized crate's `[features]` table
/// or rustc's check-cfg rejects the generated `#[cfg(feature = ...)]` code.
fn referenced_features(config: &BloxConfig) -> BTreeSet<String> {
    let mut feats = BTreeSet::new();
    if let Some(ctx) = &config.context {
        feats.extend(ctx.feature.iter().cloned());
        for u in &ctx.uses {
            feats.extend(u.feature.iter().cloned());
            for f in &u.fields {
                feats.extend(f.feature.iter().cloned());
            }
        }
        for a in &ctx.actions {
            feats.extend(a.feature.iter().cloned());
        }
    }
    if let Some(event) = &config.event {
        feats.extend(event.feature.iter().cloned());
        for m in &event.mailboxes {
            feats.extend(m.feature.iter().cloned());
        }
    }
    if let Some(topology) = &config.topology {
        for t in &topology.transitions {
            feats.extend(t.feature.iter().cloned());
        }
        for ee in topology.entry.iter().chain(topology.exit.iter()) {
            feats.extend(ee.feature.iter().cloned());
        }
    }
    feats
}

/// The `[features]` table for the materialized crate.
///
/// `[package.features]` in blox.toml wins verbatim when present. Otherwise a
/// default is synthesized: `default = ["std"]`, `std = ["bloxide-core/std"]`,
/// plus an empty feature for every feature gate referenced in the TOML
/// (e.g. `dynamic = []`).
fn crate_features(config: &BloxConfig) -> anyhow::Result<BTreeMap<String, Vec<String>>> {
    let referenced = referenced_features(config);
    let declared = config
        .package
        .as_ref()
        .map(|p| p.features.clone())
        .unwrap_or_default();

    if !declared.is_empty() {
        let missing: Vec<String> = referenced
            .iter()
            .filter(|f| !declared.contains_key(*f))
            .cloned()
            .collect();
        if !missing.is_empty() {
            anyhow::bail!(
                "blox.toml gates code on feature(s) {} but [package.features] does not declare them",
                missing
                    .iter()
                    .map(|f| format!("\"{}\"", f))
                    .collect::<Vec<_>>()
                    .join(", ")
            );
        }
        return Ok(declared);
    }

    let mut features = BTreeMap::new();
    features.insert("default".to_string(), vec!["std".to_string()]);
    features.insert("std".to_string(), vec!["bloxide-core/std".to_string()]);
    for feat in referenced {
        features.entry(feat).or_default();
    }
    Ok(features)
}

/// Parse the workspace root Cargo.toml's `[workspace.dependencies]` table:
/// crate name → workspace-relative path.
pub(crate) fn workspace_dep_paths(
    workspace_root: &Path,
) -> anyhow::Result<BTreeMap<String, String>> {
    let content = std::fs::read_to_string(workspace_root.join("Cargo.toml"))?;
    let parsed: toml::Value = toml::from_str(&content)?;
    let mut map = BTreeMap::new();
    if let Some(deps) = parsed
        .get("workspace")
        .and_then(|w| w.get("dependencies"))
        .and_then(|d| d.as_table())
    {
        for (name, value) in deps {
            if let Some(path) = value.get("path").and_then(|p| p.as_str()) {
                map.insert(name.clone(), path.to_string());
            }
        }
    }
    Ok(map)
}

/// Parse the workspace root Cargo.toml's `[workspace.package]` values used by
/// the materialized crate manifest (version, edition, license).
pub(crate) fn workspace_package_values(workspace_root: &Path) -> (String, String, Option<String>) {
    let fallback = || ("0.0.0".to_string(), "2021".to_string(), None);
    let Ok(content) = std::fs::read_to_string(workspace_root.join("Cargo.toml")) else {
        return fallback();
    };
    let Ok(parsed) = toml::from_str::<toml::Value>(&content) else {
        return fallback();
    };
    let Some(pkg) = parsed.get("workspace").and_then(|w| w.get("package")) else {
        return fallback();
    };
    let get_str = |key: &str| pkg.get(key).and_then(|v| v.as_str()).map(String::from);
    (
        get_str("version").unwrap_or_else(|| "0.0.0".to_string()),
        get_str("edition").unwrap_or_else(|| "2021".to_string()),
        get_str("license"),
    )
}

/// Resolve one crate name (underscored or hyphenated) to its
/// workspace-relative path via `[workspace.dependencies]`.
fn resolve_dep_path<'a>(
    ws_paths: &'a BTreeMap<String, String>,
    crate_name: &str,
) -> anyhow::Result<&'a str> {
    let cargo_name = crate_name.replace('_', "-");
    ws_paths.get(&cargo_name).map(String::as_str).ok_or_else(|| {
        anyhow::anyhow!(
            "dependency \"{}\" (required by the blox.toml) has no path entry in the workspace root's [workspace.dependencies]",
            cargo_name
        )
    })
}


//! Materialization of pure-TOML blox crates.
//!
//! A pure-TOML blox is a `blox.toml`-only source under a `bloxes/` directory
//! (see `util::BloxSourceKind::PureToml`). `cargo blox generate` materializes
//! a complete crate per blox into
//! `target/bloxide-generated/crates/<crate-name>/`:
//!
//! ```text
//! target/bloxide-generated/
//!   Cargo.toml                      ← generated workspace (members = ["crates/*", "examples/*"])
//!   crates/<crate-name>/
//!     Cargo.toml                    ← generated (deps derived from blox.toml)
//!     build.rs                      ← generated (re-syncs from the source blox.toml)
//!     src/lib.rs                    ← generated (no_std, prelude, consts)
//!     src/generated/*.rs            ← `generate_all` output
//!     tests/*.rs                    ← mirrored from <blox dir>/tests/
//! ```
//!
//! The crate name is the kebab-case actor name + `-blox` (`Ping` →
//! `ping-blox`). Dependencies are derived from the blox.toml sections
//! (message paths, context imports, spec imports, action crates) plus any
//! `[package.dependencies]` extras, and resolved as path dependencies via the
//! workspace root's `[workspace.dependencies]` table.
//!
//! Every write goes through `write_if_changed` so repeated `cargo blox
//! generate` runs (and the generated `build.rs` re-sync) are byte-identical
//! and mtime-stable.

use crate::schema::{BloxConfig, DepSpec, SystemConfig};
use crate::system_wiring::{extract_crates_from_path, rustfmt_source};
use crate::util;
use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};

/// Workspace-relative directory holding the generated blox-crate workspace.
pub const GENERATED_WORKSPACE_DIR: &str = "target/bloxide-generated";

/// Manifest path (repo-relative) of the bloxide-codegen crate — every
/// materialized crate build-depends on it so its build.rs can re-sync.
const CODEGEN_CRATE_PATH: &str = "crates/tools/bloxide-codegen";

const MANIFEST_HEADER: &str = "# Copyright 2025 Bloxide, all rights reserved\n\
     # Auto-generated by bloxide-codegen from blox.toml — do not edit by hand; regenerate with `cargo blox generate`.\n";

/// Header for the generated WORKSPACE root manifest (covers both blox crates
/// and example crates).
const WORKSPACE_MANIFEST_HEADER: &str = "# Copyright 2025 Bloxide, all rights reserved\n\
     # Auto-generated by bloxide-codegen from blox.toml / system.toml — do not edit by hand; regenerate with `cargo blox generate`.\n";

